namespace PhpCsFixer\Fixer\Phpdoc;

use PhpCsFixer\AbstractFixer;
use PhpCsFixer\DocBlock\DocBlock;
use PhpCsFixer\Fixer\ConfigurableFixerInterface;
use PhpCsFixer\Fixer\ConfigurableFixerTrait;
use PhpCsFixer\Fixer\WhitespacesAwareFixerInterface;
use PhpCsFixer\FixerConfiguration\FixerConfigurationResolver;
use PhpCsFixer\FixerConfiguration\FixerConfigurationResolverInterface;
use PhpCsFixer\FixerConfiguration\FixerOptionBuilder;
use PhpCsFixer\FixerDefinition\CodeSample;
use PhpCsFixer\FixerDefinition\FixerDefinition;
use PhpCsFixer\FixerDefinition\FixerDefinitionInterface;
use PhpCsFixer\Tokenizer\Token;
use PhpCsFixer\Tokenizer\Tokens;

/**
 * @phpstan-type _AutogeneratedInputConfiguration array{
 *  format?: 'multi'|'union',
 * }
 * @phpstan-type _AutogeneratedComputedConfiguration array{
 *  format: 'multi'|'union',
 * }
 *
 * @implements ConfigurableFixerInterface<_AutogeneratedInputConfiguration, _AutogeneratedComputedConfiguration>
 *
 * @no-named-arguments Parameter names are not covered by the backward compatibility promise.
 */
final class PhpdocMultiLineThrowsFixer extends AbstractFixer implements ConfigurableFixerInterface, WhitespacesAwareFixerInterface
{
    /** @use ConfigurableFixerTrait<_AutogeneratedInputConfiguration, _AutogeneratedComputedConfiguration> */
    use ConfigurableFixerTrait;

    public function getDefinition(): FixerDefinitionInterface
    {
        $code = <<<'EOF'
            <?php
            /**
             * @throws InvalidArgumentException|RuntimeException
             * @throws DivisionByZeroException
             * @throws Throwable&Exception
             * @throws OutOfBoundsException with a comment about this specific exception
             * @throws OverFlowException|RangeException with a comment about this specific union exception
             */

            EOF;

        return new FixerDefinition(
            'Throws annotations should be either in union or multiline format.',
            [
                new CodeSample($code),
                new CodeSample($code, ['format' => 'union']),
                new CodeSample($code, ['format' => 'multi']),
            ],
            'Formatting is only applied on lines without comments. Intersection types are preserved when one of the union types is an intersection type of itself.',
        );
    }

    public function isCandidate(Tokens $tokens): bool
    {
        return $tokens->isTokenKindFound(\T_DOC_COMMENT);
    }

    /**
     * {@inheritdoc}
     *
     * Must run before PhpdocAlignFixer.
     * Must run after AlignMultilineCommentFixer, CommentToPhpdocFixer, PhpdocIndentFixer, PhpdocScalarFixer, PhpdocToCommentFixer, PhpdocTypesFixer.
     */
    public function getPriority(): int
    {
        return 10;
    }

    protected function createConfigurationDefinition(): FixerConfigurationResolverInterface
    {
        return new FixerConfigurationResolver([
            (new FixerOptionBuilder('format', 'Whether to use union or multiline.'))
                ->setAllowedValues(['union', 'multi'])
                ->setDefault('union')
                ->getOption(),
        ]);
    }

    protected function applyFix(\SplFileInfo $file, Tokens $tokens): void
    {
        foreach ($tokens as $index => $token) {
            if (!$token->isGivenKind(\T_DOC_COMMENT)) {
                continue;
            }

            $candidates = [];
            $doc = new DocBlock($token->getContent());
            foreach ($doc->getAnnotationsOfType('throws') as $throwsAnnotation) {
                $commentOnSpecificThrows = trim(str_replace(['*', '@throws', $throwsAnnotation->getTypeExpression()->toString()], '', $throwsAnnotation->getContent()));
                if ('' === $commentOnSpecificThrows) {
                    $candidates[] = $throwsAnnotation;
                }
            }

            if ('union' === $this->configuration['format']) {
                if (\count($candidates) < 2) {
                    continue;
                }

                $typeStrings = [];
                foreach ($candidates as $candidate) {
                    $candidateType = $candidate->getTypeExpression();
                    $typeStrings[] = ($candidateType->isIntersectionType() ? '(' : '')
                        .$candidateType->toString()
                        .($candidateType->isIntersectionType() ? ')' : '');
                }

                $doc->getLine($candidates[0]->getStart())
                    ->setContent(str_replace($candidates[0]->getTypeExpression()->toString(), implode('|', $typeStrings), $candidates[0]->getContent()))
                ;
                foreach (\array_slice($candidates, 1) as $otherCandidate) {
                    $otherCandidate->remove();
                }
            } elseif ('multi' === $this->configuration['format']) {
                foreach ($candidates as $candidate) {
                    $candidateType = $candidate->getTypeExpression();
                    if ($candidateType->isIntersectionType() || \count($candidateType->getTypes()) < 2) {
                        continue;
                    }

                    $line = $doc->getLine($candidate->getStart());
                    $lineEnding = $this->whitespacesConfig->getLineEnding();
                    $leading = str_replace([$candidateType->toString(), $lineEnding], '', $line->getContent());
                    $line->setContent($leading.implode($lineEnding.$leading, $candidateType->getTypes()).$lineEnding);
                }
            }

            $tokens[$index] = new Token([\T_DOC_COMMENT, $doc->getContent()]);
        }
    }
}
