namespace PhpCsFixer\Fixer\Phpdoc;

use PhpCsFixer\AbstractFixer;
use PhpCsFixer\DocBlock\Annotation;
use PhpCsFixer\DocBlock\DocBlock;
use PhpCsFixer\DocBlock\TypeExpression;
use PhpCsFixer\Fixer\ConfigurableFixerInterface;
use PhpCsFixer\Fixer\ConfigurableFixerTrait;
use PhpCsFixer\FixerConfiguration\FixerConfigurationResolver;
use PhpCsFixer\FixerConfiguration\FixerConfigurationResolverInterface;
use PhpCsFixer\FixerConfiguration\FixerOptionBuilder;
use PhpCsFixer\FixerDefinition\CodeSample;
use PhpCsFixer\FixerDefinition\FixerDefinition;
use PhpCsFixer\FixerDefinition\FixerDefinitionInterface;
use PhpCsFixer\Preg;
use PhpCsFixer\Tokenizer\Token;
use PhpCsFixer\Tokenizer\Tokens;

/**
 * @phpstan-type _AutogeneratedInputConfiguration array{
 *  syntax?: 'question_mark'|'union',
 * }
 * @phpstan-type _AutogeneratedComputedConfiguration array{
 *  syntax: 'question_mark'|'union',
 * }
 *
 * @implements ConfigurableFixerInterface<_AutogeneratedInputConfiguration, _AutogeneratedComputedConfiguration>
 *
 * @no-named-arguments Parameter names are not covered by the backward compatibility promise.
 */
final class PhpdocNullableTypeFixer extends AbstractFixer implements ConfigurableFixerInterface
{
    /** @use ConfigurableFixerTrait<_AutogeneratedInputConfiguration, _AutogeneratedComputedConfiguration> */
    use ConfigurableFixerTrait;

    private const OPTION_SYNTAX_QUESTION_MARK = 'question_mark';
    private const OPTION_SYNTAX_UNION = 'union';

    public function getDefinition(): FixerDefinitionInterface
    {
        return new FixerDefinition(
            'Nullable PHPDoc types should be standardised using configured syntax.',
            [
                new CodeSample(
                    <<<'PHP'
                        <?php
                        /** @var null|Foo */

                        PHP,
                ),
                new CodeSample(
                    <<<'PHP'
                        <?php
                        /** @var ?Foo */

                        PHP,
                    ['syntax' => self::OPTION_SYNTAX_UNION],
                ),
            ],
        );
    }

    /**
     * {@inheritdoc}
     *
     * Must run before PhpdocAlignFixer.
     * Must run after AlignMultilineCommentFixer, CommentToPhpdocFixer, PhpdocIndentFixer, PhpdocScalarFixer, PhpdocToCommentFixer, PhpdocTypesFixer.
     */
    public function getPriority(): int
    {
        return 0;
    }

    public function isCandidate(Tokens $tokens): bool
    {
        return $tokens->isTokenKindFound(\T_DOC_COMMENT);
    }

    protected function createConfigurationDefinition(): FixerConfigurationResolverInterface
    {
        return new FixerConfigurationResolver([
            (new FixerOptionBuilder(
                'syntax',
                'Whether to use question mark (`?`) or explicit `null` union for nullable PHPDoc types.',
            ))
                ->setAllowedValues([
                    self::OPTION_SYNTAX_QUESTION_MARK,
                    self::OPTION_SYNTAX_UNION,
                ])
                ->setDefault(self::OPTION_SYNTAX_QUESTION_MARK)
                ->getOption(),
        ]);
    }

    protected function applyFix(\SplFileInfo $file, Tokens $tokens): void
    {
        foreach ($tokens as $index => $token) {
            if (!$token->isGivenKind(\T_DOC_COMMENT)) {
                continue;
            }

            $doc = new DocBlock($token->getContent());

            foreach ($doc->getAnnotationsOfType(Annotation::TAGS_WITH_TYPES) as $annotation) {
                $typeExpression = $annotation->getTypeExpression();

                if (null !== $typeExpression) {
                    $normalized = $this->normalizeTypeExpression($typeExpression);

                    $annotation->setTypes([$normalized->toString()]);
                }

                if ('method' !== $annotation->getTag()->getName()) {
                    continue;
                }

                $line = $doc->getLine($annotation->getStart());

                $line->setContent(
                    Preg::replaceCallback(
                        '/\*\h*@method\h+'.TypeExpression::REGEX_TYPES.'\h+\K(?&callable)/',
                        function (array $matches): string {
                            \assert(isset($matches[0]));

                            return $this
                                ->normalizeTypeExpression(new TypeExpression($matches[0], null, []))
                                ->toString()
                            ;
                        },
                        $line->getContent(),
                    ),
                );
            }

            $tokens[$index] = new Token([\T_DOC_COMMENT, $doc->getContent()]);
        }
    }

    private function normalizeTypeExpression(TypeExpression $typeExpression): TypeExpression
    {
        if (self::OPTION_SYNTAX_UNION === $this->configuration['syntax']) {
            $typeExpression = $this->removeRedundantNullableSyntaxFromUnions($typeExpression);
        }

        return $typeExpression->mapTypes(function (TypeExpression $type): TypeExpression {
            if (self::OPTION_SYNTAX_QUESTION_MARK === $this->configuration['syntax']) {
                return $this->toQuestionMarkSyntax($type);
            }

            return $this->toUnionSyntax($type);
        });
    }

    private function removeRedundantNullableSyntaxFromUnions(TypeExpression $typeExpression): TypeExpression
    {
        return $typeExpression->mapTypes(static function (TypeExpression $type): TypeExpression {
            if (!$type->isUnionType()) {
                return $type;
            }

            $types = $type->getTypes();

            $hasNull = false;

            foreach ($types as $unionType) {
                if ('null' === strtolower($unionType)) {
                    $hasNull = true;

                    break;
                }
            }

            if (!$hasNull) {
                return $type;
            }

            $changed = false;

            foreach ($types as $index => $unionType) {
                if (!str_starts_with($unionType, '?')) {
                    continue;
                }

                $types[$index] = substr($unionType, 1);
                $changed = true;
            }

            if (!$changed) {
                return $type;
            }

            return new TypeExpression(implode('|', $types), null, []);
        });
    }

    private function toQuestionMarkSyntax(TypeExpression $type): TypeExpression
    {
        if (!$type->isUnionType()) {
            return $type;
        }

        $types = $type->getTypes();

        if (2 !== \count($types)) {
            return $type;
        }

        $firstIsNull = 'null' === strtolower($types[0]);
        $secondIsNull = 'null' === strtolower($types[1]);

        if ($firstIsNull === $secondIsNull) {
            return $type;
        }

        $nonNullType = $firstIsNull ? $types[1] : $types[0];

        if (str_starts_with($nonNullType, '?')) {
            return new TypeExpression($nonNullType, null, []);
        }

        $nonNullTypeExpression = new TypeExpression($nonNullType, null, []);

        if ($nonNullTypeExpression->isCompositeType()) {
            $nonNullType = '('.$nonNullType.')';
        }

        return new TypeExpression('?'.$nonNullType, null, []);
    }

    private function toUnionSyntax(TypeExpression $type): TypeExpression
    {
        $value = $type->toString();

        if ($type->isCompositeType() || !str_starts_with($value, '?')) {
            return $type;
        }

        return new TypeExpression('null|'.substr($value, 1), null, []);
    }
}
