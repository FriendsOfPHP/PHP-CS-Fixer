namespace PhpCsFixer\Fixer\Basic;

use PhpCsFixer\AbstractFixer;
use PhpCsFixer\Fixer\ConfigurableFixerInterface;
use PhpCsFixer\Fixer\ConfigurableFixerTrait;
use PhpCsFixer\FixerConfiguration\FixerConfigurationResolver;
use PhpCsFixer\FixerConfiguration\FixerConfigurationResolverInterface;
use PhpCsFixer\FixerConfiguration\FixerOptionBuilder;
use PhpCsFixer\FixerDefinition\CodeSample;
use PhpCsFixer\FixerDefinition\FixerDefinition;
use PhpCsFixer\FixerDefinition\FixerDefinitionInterface;
use PhpCsFixer\FixerDefinition\VersionSpecification;
use PhpCsFixer\FixerDefinition\VersionSpecificCodeSample;
use PhpCsFixer\Tokenizer\FCT;
use PhpCsFixer\Tokenizer\Token;
use PhpCsFixer\Tokenizer\Tokens;

/**
 * @phpstan-type _AutogeneratedInputConfiguration array{
 *  classy?: bool,
 *  constructors_multi_line?: bool,
 *  constructors_single_line?: bool,
 *  functions?: bool,
 * }
 * @phpstan-type _AutogeneratedComputedConfiguration array{
 *  classy: bool,
 *  constructors_multi_line: bool,
 *  constructors_single_line: bool,
 *  functions: bool,
 * }
 *
 * @implements ConfigurableFixerInterface<_AutogeneratedInputConfiguration, _AutogeneratedComputedConfiguration>
 *
 * @no-named-arguments Parameter names are not covered by the backward compatibility promise.
 */
final class SingleLineEmptyBodyFixer extends AbstractFixer implements ConfigurableFixerInterface
{
    /** @use ConfigurableFixerTrait<_AutogeneratedInputConfiguration, _AutogeneratedComputedConfiguration> */
    use ConfigurableFixerTrait;

    public function getDefinition(): FixerDefinitionInterface
    {
        return new FixerDefinition(
            'Empty body of class, interface, trait, enum or function must be abbreviated as `{}` and placed on the same line as the previous symbol, separated by a single space.',
            [
                new CodeSample(
                    <<<'PHP'
                        <?php function foo(
                            int $x
                        )
                        {
                        }

                        PHP,
                ),
                new CodeSample(
                    <<<'PHP'
                        <?php
                        class Foo
                        {
                        }

                        function foo()
                        {
                        }

                        PHP,
                    ['classy' => false],
                ),
                new VersionSpecificCodeSample(
                    <<<'PHP'
                        <?php
                        class Foo
                        {
                            public function __construct(private int $x)
                            {
                            }
                        }

                        PHP,
                    new VersionSpecification(8_00_00),
                    ['constructors_single_line' => true, 'constructors_multi_line' => false, 'classy' => false],
                ),
            ],
        );
    }

    /**
     * {@inheritdoc}
     *
     * Must run after BracesPositionFixer, ClassDefinitionFixer, CurlyBracesPositionFixer, NoUselessReturnFixer.
     */
    public function getPriority(): int
    {
        return -19;
    }

    public function isCandidate(Tokens $tokens): bool
    {
        return $tokens->isAnyTokenKindsFound([\T_INTERFACE, \T_CLASS, \T_FUNCTION, \T_TRAIT, FCT::T_ENUM]);
    }

    protected function createConfigurationDefinition(): FixerConfigurationResolverInterface
    {
        return new FixerConfigurationResolver([
            (new FixerOptionBuilder('classy', 'Whether to fix empty bodies of classes, interfaces, traits and enums.'))
                ->setAllowedTypes(['bool'])
                ->setDefault(true)
                ->getOption(),
            (new FixerOptionBuilder('constructors_single_line', 'Whether to fix empty bodies of constructors whose parameters are on a single line.'))
                ->setAllowedTypes(['bool'])
                ->setDefault(true)
                ->getOption(),
            (new FixerOptionBuilder('constructors_multi_line', 'Whether to fix empty bodies of constructors whose parameters span multiple lines.'))
                ->setAllowedTypes(['bool'])
                ->setDefault(true)
                ->getOption(),
            (new FixerOptionBuilder('functions', 'Whether to fix empty bodies of functions and methods other than constructors.'))
                ->setAllowedTypes(['bool'])
                ->setDefault(true)
                ->getOption(),
        ]);
    }

    protected function applyFix(\SplFileInfo $file, Tokens $tokens): void
    {
        for ($index = $tokens->count() - 1; $index > 0; --$index) {
            if (!$tokens[$index]->isGivenKind([...Token::getClassyTokenKinds(), \T_FUNCTION])) {
                continue;
            }

            if (!$this->isEnabled($tokens, $index)) {
                continue;
            }

            $openBraceIndex = $tokens->getNextTokenOfKind($index, ['{', ';']);
            if (!$tokens[$openBraceIndex]->equals('{')) {
                continue;
            }

            $closeBraceIndex = $tokens->getNextNonWhitespace($openBraceIndex);
            if (!$tokens[$closeBraceIndex]->equals('}')) {
                continue;
            }

            $tokens->ensureWhitespaceAtIndex($openBraceIndex + 1, 0, '');

            $beforeOpenBraceIndex = $tokens->getPrevNonWhitespace($openBraceIndex);
            if (!$tokens[$beforeOpenBraceIndex]->isGivenKind([\T_COMMENT, \T_DOC_COMMENT])) {
                $tokens->ensureWhitespaceAtIndex($openBraceIndex - 1, 1, ' ');
            }
        }
    }

    private function isEnabled(Tokens $tokens, int $index): bool
    {
        if (!$tokens[$index]->isGivenKind(\T_FUNCTION)) {
            return $this->configuration['classy'];
        }

        $nameIndex = $tokens->getNextMeaningfulToken($index);
        if (!$tokens[$nameIndex]->equals([\T_STRING, '__construct'], false)) {
            return $this->configuration['functions'];
        }

        $parenthesisStart = $tokens->getNextMeaningfulToken($nameIndex);
        $parenthesisEnd = $tokens->findBlockEnd(Tokens::BLOCK_TYPE_PARENTHESIS, $parenthesisStart);

        for ($i = $parenthesisStart; $i < $parenthesisEnd; ++$i) {
            if ($tokens[$i]->isWhitespace() && str_contains($tokens[$i]->getContent(), "\n")) {
                return $this->configuration['constructors_multi_line'];
            }
        }

        return $this->configuration['constructors_single_line'];
    }
}
