/**
 * Let's you add underscores to numeric literals.
 *
 * Inspired by:
 * - {@link https://github.com/kubawerlos/php-cs-fixer-custom-fixers/blob/main/src/Fixer/NumericLiteralSeparatorFixer.php}
 * - {@link https://github.com/sindresorhus/eslint-plugin-unicorn/blob/main/rules/numeric-separators-style.js}
 *
 * @phpstan-type _AutogeneratedInputConfiguration array{
 *  minimum_digits?: array<string, int>,
 *  override_existing?: bool,
 *  strategy?: 'no_separator'|'use_separator',
 *  types?: list<'binary'|'decimal'|'float'|'hexadecimal'|'octal'>,
 * }
 * @phpstan-type _AutogeneratedComputedConfiguration array{
 *  minimum_digits: array<string, int>,
 *  override_existing: bool,
 *  strategy: 'no_separator'|'use_separator',
 *  types: list<'binary'|'decimal'|'float'|'hexadecimal'|'octal'>,
 * }
 *
 * @implements ConfigurableFixerInterface<_AutogeneratedInputConfiguration, _AutogeneratedComputedConfiguration>
 *
 * @author Marvin Heilemann <marvin.heilemann+github@googlemail.com>
 * @author Greg Korba <greg@codito.dev>
 *
 * @no-named-arguments Parameter names are not covered by the backward compatibility promise.
 */
final class NumericLiteralSeparatorFixer extends AbstractFixer implements ConfigurableFixerInterface
{
    /** @use ConfigurableFixerTrait<_AutogeneratedInputConfiguration, _AutogeneratedComputedConfiguration> */
    use ConfigurableFixerTrait;

    public const STRATEGY_USE_SEPARATOR = 'use_separator';
    public const STRATEGY_NO_SEPARATOR = 'no_separator';

    private const TYPES = ['binary', 'decimal', 'float', 'hexadecimal', 'octal'];

    public function getDefinition(): FixerDefinitionInterface
    {
        return new FixerDefinition(
            'Adds separators to numeric literals of any kind.',
            [
                new CodeSample(
                    <<<'PHP'
                        <?php
                        $integer = 1234567890;

                        PHP,
                ),
                new CodeSample(
                    <<<'PHP'
                        <?php
                        $integer = 1234_5678;
                        $octal = 01_234_56;
                        $binary = 0b00_10_01_00;
                        $hexadecimal = 0x3D45_8F4F;

                        PHP,
                    ['strategy' => self::STRATEGY_NO_SEPARATOR],
                ),
                new CodeSample(
                    <<<'PHP'
                        <?php
                        $integer = 12345678;
                        $octal = 0123456;
                        $binary = 0b0010010011011010;
                        $hexadecimal = 0x3D458F4F;

                        PHP,
                    ['strategy' => self::STRATEGY_USE_SEPARATOR],
                ),
                new CodeSample(
                    "<?php \$var = 24_40_21;\n",
                    ['override_existing' => true],
                ),
                new CodeSample(
                    <<<'PHP'
                        <?php
                        $integer = 12345678;
                        $float = 1234.5678;
                        $hexadecimal = 0x3D458F4F;

                        PHP,
                    ['types' => ['decimal', 'hexadecimal']],
                ),
                new CodeSample(
                    <<<'PHP'
                        <?php
                        $integer = 1234;
                        $largerInteger = 12345;
                        $float = 1234.56789;

                        PHP,
                    ['minimum_digits' => ['decimal' => 5, 'float' => 5]],
                ),
            ],
        );
    }

    public function isCandidate(Tokens $tokens): bool
    {
        return $tokens->isAnyTokenKindsFound([\T_DNUMBER, \T_LNUMBER]);
    }

    protected function createConfigurationDefinition(): FixerConfigurationResolverInterface
    {
        return new FixerConfigurationResolver([
            (new FixerOptionBuilder(
                'minimum_digits',
                'Dictionary of `type` => `minimum digits` a part of the literal (integer, fraction or exponent) must have to get separators; unlisted types use `0`. Only applies when `strategy` is `use_separator`.',
            ))
                ->setAllowedTypes(['array<string, int>'])
                ->setAllowedValues([static function (array $option): bool {
                    foreach ($option as $type => $minimumDigits) {
                        if (!\in_array($type, self::TYPES, true)) {
                            throw new InvalidOptionsException(\sprintf(
                                'Unexpected "minimum_digits" key, expected any of %s, got "%s".',
                                Utils::naturalLanguageJoin(self::TYPES),
                                $type,
                            ));
                        }

                        if ($minimumDigits < 0) {
                            throw new InvalidOptionsException(\sprintf(
                                'Unexpected "minimum_digits" value for "%s", expected a non-negative integer, got %d.',
                                $type,
                                $minimumDigits,
                            ));
                        }
                    }

                    return true;
                }])
                ->setDefault([])
                ->getOption(),
            (new FixerOptionBuilder(
                'override_existing',
                'Whether literals already containing underscores should be reformatted.',
            ))
                ->setAllowedTypes(['bool'])
                ->setDefault(false)
                ->getOption(),
            (new FixerOptionBuilder(
                'strategy',
                'Whether numeric literal should be separated by underscores or not.',
            ))
                ->setAllowedValues([self::STRATEGY_USE_SEPARATOR, self::STRATEGY_NO_SEPARATOR])
                ->setDefault(self::STRATEGY_USE_SEPARATOR)
                ->getOption(),
            (new FixerOptionBuilder(
                'types',
                'Which types of numeric literals should be processed.',
            ))
                ->setAllowedTypes(['string[]'])
                ->setAllowedValues([new AllowedValueSubset(self::TYPES)])
                ->setDefault(self::TYPES)
                ->getOption(),
        ]);
    }

    protected function applyFix(\SplFileInfo $file, Tokens $tokens): void
    {
        foreach ($tokens as $index => $token) {
            if (!$token->isGivenKind([\T_DNUMBER, \T_LNUMBER])) {
                continue;
            }

            $content = $token->getContent();
            $type = self::getType($content);

            if (!\in_array($type, $this->configuration['types'], true)) {
                continue;
            }

            $newContent = $this->formatValue($content, $type);

            if ($content === $newContent) {
                // Skip Token override if its the same content, like when it
                // already got a valid literal separator structure.
                continue;
            }

            $tokens[$index] = new Token([$token->getId(), $newContent]);
        }
    }

    private static function getType(string $value): string
    {
        $lowerValue = strtolower($value);

        if (str_starts_with($lowerValue, '0x')) {
            return 'hexadecimal';
        }

        if (str_starts_with($lowerValue, '0b')) {
            return 'binary';
        }

        if (str_starts_with($lowerValue, '0o')) {
            return 'octal';
        }

        if (str_contains($lowerValue, '.') || str_contains($lowerValue, 'e')) {
            return 'float';
        }

        if (str_starts_with($lowerValue, '0')) {
            // Octal notation prior PHP 8.1 but still valid
            return 'octal';
        }

        return 'decimal';
    }

    private function formatValue(string $value, string $type): string
    {
        if (self::STRATEGY_NO_SEPARATOR === $this->configuration['strategy']) {
            return str_contains($value, '_') ? str_replace('_', '', $value) : $value;
        }

        if (true === $this->configuration['override_existing']) {
            $value = str_replace('_', '', $value);
        } elseif (str_contains($value, '_')) {
            // Keep already underscored literals untouched.
            return $value;
        }

        $minimumDigits = $this->configuration['minimum_digits'][$type] ?? 0;

        if ('binary' === $type) {
            return $this->insertEveryRight($value, 8, 2, $minimumDigits);
        }

        if ('hexadecimal' === $type) {
            return $this->insertEveryRight($value, 2, 2, $minimumDigits);
        }

        if ('octal' === $type) {
            return $this->insertEveryRight($value, 3, str_starts_with(strtolower($value), '0o') ? 2 : 1, $minimumDigits);
        }

        // Decimal and float

        /** If its a signed value we need an offset */
        $signOffset = static fn (string $v): int => str_contains($v, '-') || str_contains($v, '+') ? 1 : 0;

        Preg::matchAll('/([0-9-_]+)?((\.)([0-9_]*))?((e)([+-]?[0-9_]+))?/i', $value, $result);
        \assert(isset($result[1][0], $result[3][0], $result[4][0], $result[6][0], $result[7][0]));

        $integer = $result[1][0];
        $joinedValue = $this->insertEveryRight($integer, 3, $signOffset($integer), $minimumDigits);

        $dot = $result[3][0];
        if ('' !== $dot) {
            $integer = $result[4][0];
            $decimal = $this->insertEveryLeft($integer, 3, $signOffset($integer), $minimumDigits);
            $joinedValue = $joinedValue.$dot.$decimal;
        }

        $tim = $result[6][0];
        if ('' !== $tim) {
            $integer = $result[7][0];
            $times = $this->insertEveryRight($integer, 3, $signOffset($integer), $minimumDigits);
            $joinedValue = $joinedValue.$tim.$times;
        }

        return $joinedValue;
    }

    private function insertEveryRight(string $value, int $length, int $offset, int $minimumDigits): string
    {
        if (\strlen($value) - $offset < $minimumDigits) {
            return $value;
        }

        $position = $length * -1;
        while ($position > -(\strlen($value) - $offset)) {
            $value = substr_replace($value, '_', $position, 0);
            $position -= $length + 1;
        }

        return $value;
    }

    private function insertEveryLeft(string $value, int $length, int $offset, int $minimumDigits): string
    {
        if (\strlen($value) < $minimumDigits) {
            return $value;
        }

        $position = $length;
        while ($position < \strlen($value)) {
            $value = substr_replace($value, '_', $position, $offset);
            $position += $length + 1;
        }

        return $value;
    }
}
