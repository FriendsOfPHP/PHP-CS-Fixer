namespace PhpCsFixer\Fixer\Whitespace;

use PhpCsFixer\AbstractFixer;
use PhpCsFixer\Fixer\ConfigurableFixerInterface;
use PhpCsFixer\Fixer\ConfigurableFixerTrait;
use PhpCsFixer\FixerConfiguration\FixerConfigurationResolver;
use PhpCsFixer\FixerConfiguration\FixerConfigurationResolverInterface;
use PhpCsFixer\FixerConfiguration\FixerOptionBuilder;
use PhpCsFixer\FixerDefinition\CodeSample;
use PhpCsFixer\FixerDefinition\FixerDefinition;
use PhpCsFixer\FixerDefinition\FixerDefinitionInterface;
use PhpCsFixer\Tokenizer\CT;
use PhpCsFixer\Tokenizer\Token;
use PhpCsFixer\Tokenizer\Tokens;
use PhpCsFixer\Utils;
use Symfony\Component\OptionsResolver\Exception\InvalidOptionsException;
use Symfony\Component\OptionsResolver\Options;

/**
 * @phpstan-type _AutogeneratedInputConfiguration array{
 *  spacing?: array<string, string>,
 * }
 * @phpstan-type _AutogeneratedComputedConfiguration array{
 *  spacing: array<string, string>,
 * }
 *
 * @implements ConfigurableFixerInterface<_AutogeneratedInputConfiguration, _AutogeneratedComputedConfiguration>
 *
 * @no-named-arguments Parameter names are not covered by the backward compatibility promise.
 */
final class SpacesAroundOffsetFixer extends AbstractFixer implements ConfigurableFixerInterface
{
    /** @use ConfigurableFixerTrait<_AutogeneratedInputConfiguration, _AutogeneratedComputedConfiguration> */
    use ConfigurableFixerTrait;

    /**
     * @internal
     */
    public const SPACING_NONE = 'none';

    /**
     * @internal
     */
    public const SPACING_SINGLE = 'single';

    /**
     * @internal
     */
    public const SPACING_IGNORE = 'ignore';

    private const POSITIONS = ['inside', 'outside'];

    private const SPACINGS = [self::SPACING_NONE, self::SPACING_SINGLE, self::SPACING_IGNORE];

    private const DEFAULT_SPACING = [
        'inside' => self::SPACING_NONE,
        'outside' => self::SPACING_NONE,
    ];

    public function getDefinition(): FixerDefinitionInterface
    {
        return new FixerDefinition(
            'There must be no space, or a single space, inside and outside of offset braces, as configured.',
            [
                new CodeSample("<?php\n\$sample = \$b [ 'a' ] [ 'b' ];\n"),
                new CodeSample("<?php\n\$sample = \$b['a']['b'];\n", ['spacing' => ['inside' => self::SPACING_SINGLE, 'outside' => self::SPACING_SINGLE]]),
                new CodeSample("<?php\n\$sample = \$b [ 'a' ] [ 'b' ];\n", ['spacing' => ['inside' => self::SPACING_SINGLE]]),
                new CodeSample("<?php\n\$sample = \$b [ 'a' ] [ 'b' ];\n", ['spacing' => ['inside' => self::SPACING_NONE, 'outside' => self::SPACING_IGNORE]]),
                new CodeSample("<?php\n\$sample = \$b [ 'a' ] [ 'b' ];\n", ['spacing' => ['inside' => self::SPACING_IGNORE, 'outside' => self::SPACING_NONE]]),
            ],
            'Whitespace containing a line break is preserved inside the braces, and outside of them when `single` is configured. Offsets in simple string interpolation (e.g. `"$a[1]"`) are never changed.',
        );
    }

    public function isCandidate(Tokens $tokens): bool
    {
        return $tokens->isAnyTokenKindsFound(['[', CT::T_ARRAY_INDEX_BRACE_OPEN]);
    }

    protected function applyFix(\SplFileInfo $file, Tokens $tokens): void
    {
        $inside = $this->configuration['spacing']['inside'] ?? self::DEFAULT_SPACING['inside'];
        $outside = $this->configuration['spacing']['outside'] ?? self::DEFAULT_SPACING['outside'];

        if (self::SPACING_IGNORE === $inside && self::SPACING_IGNORE === $outside) {
            return;
        }

        $openIndices = $this->findOffsetOpenIndices($tokens);

        // process backwards, so inserting tokens does not shift indices not processed yet
        foreach (array_reverse($openIndices) as $index) {
            $endIndex = $tokens->findBlockEnd(
                $tokens[$index]->equals('[') ? Tokens::BLOCK_TYPE_INDEX_BRACKET : Tokens::BLOCK_TYPE_INDEX_BRACE,
                $index,
            );

            if (self::SPACING_IGNORE !== $inside) {
                $this->fixInside($tokens, $index, $endIndex, $inside);
            }

            if (self::SPACING_IGNORE !== $outside) {
                $this->fixOutside($tokens, $index, $outside);
            }
        }
    }

    protected function createConfigurationDefinition(): FixerConfigurationResolverInterface
    {
        return new FixerConfigurationResolver([
            (new FixerOptionBuilder('spacing', 'Dictionary of `inside|outside` => `none|single|ignore` values.'))
                ->setAllowedTypes(['array<string, string>'])
                ->setAllowedValues([static function (array $option): bool {
                    foreach ($option as $position => $spacing) {
                        if (!\in_array($position, self::POSITIONS, true)) {
                            throw new InvalidOptionsException(
                                \sprintf(
                                    'Unexpected position, expected any of %s, got "%s".',
                                    Utils::naturalLanguageJoin(self::POSITIONS),
                                    \gettype($position).'#'.$position,
                                ),
                            );
                        }

                        if (!\in_array($spacing, self::SPACINGS, true)) {
                            throw new InvalidOptionsException(
                                \sprintf(
                                    'Unexpected spacing for position "%s", expected any of %s, got "%s".',
                                    $position,
                                    Utils::naturalLanguageJoin(self::SPACINGS),
                                    \is_object($spacing) ? \get_class($spacing) : (null === $spacing ? 'null' : \gettype($spacing).'#'.$spacing),
                                ),
                            );
                        }
                    }

                    return true;
                }])
                ->setNormalizer(static fn (Options $options, array $value): array => array_merge(self::DEFAULT_SPACING, $value))
                ->setDefault(self::DEFAULT_SPACING)
                ->getOption(),
        ]);
    }

    /**
     * Finds the indices of all offset opening braces, skipping the ones used in simple string interpolation
     * (e.g. `"$a[1]"`), where whitespace is not allowed.
     *
     * @return list<int>
     */
    private function findOffsetOpenIndices(Tokens $tokens): array
    {
        $indices = [];

        /** @var list<bool> $stack true when inside a string, false when inside code embedded in a string */
        $stack = [];

        foreach ($tokens as $index => $token) {
            $inString = [] !== $stack && true === end($stack);

            if ($token->equalsAny(['"', '`'])) {
                if ($inString) {
                    array_pop($stack);
                } else {
                    $stack[] = true;
                }

                continue;
            }

            if ($token->isGivenKind(\T_START_HEREDOC)) {
                $stack[] = true;

                continue;
            }

            if ($token->isGivenKind(\T_END_HEREDOC)) {
                array_pop($stack);

                continue;
            }

            if ($token->isGivenKind([\T_CURLY_OPEN, \T_DOLLAR_OPEN_CURLY_BRACES])) {
                $stack[] = false;

                continue;
            }

            if ($token->isGivenKind([CT::T_CURLY_CLOSE, CT::T_DOLLAR_CLOSE_CURLY_BRACES])) {
                array_pop($stack);

                continue;
            }

            if ($inString) {
                continue;
            }

            if ($token->equalsAny(['[', [CT::T_ARRAY_INDEX_BRACE_OPEN]])) {
                $indices[] = $index;
            }
        }

        return $indices;
    }

    private function fixInside(Tokens $tokens, int $index, int $endIndex, string $spacing): void
    {
        // empty offset, e.g. `$a[]` or `$a[  ]`, never gets a space
        if ($endIndex === $index + 1) {
            return;
        }

        if ($endIndex === $index + 2 && $tokens[$index + 1]->isWhitespace()) {
            if ($tokens[$index + 1]->isWhitespace(" \t")) {
                $tokens->clearAt($index + 1);
            }

            return;
        }

        // space before closing `]` or `}`; done first as it does not shift `$index`
        $this->fixSpaceAt($tokens, $endIndex, $endIndex - 1, $spacing, false);

        // space after opening `[` or `{`
        $this->fixSpaceAt($tokens, $index + 1, $index + 1, $spacing, false);
    }

    private function fixOutside(Tokens $tokens, int $index, string $spacing): void
    {
        $prevNonWhitespaceIndex = $tokens->getPrevNonWhitespace($index);

        if (null === $prevNonWhitespaceIndex || $tokens[$prevNonWhitespaceIndex]->isComment()) {
            return;
        }

        $this->fixSpaceAt($tokens, $index, $index - 1, $spacing, true);
    }

    /**
     * @param int  $insertIndex               index at which a space is inserted when there is none
     * @param int  $whitespaceIndex           index of the token that is the candidate whitespace
     * @param bool $removeMultilineWhitespace whether whitespace containing a line break is removed for `none` spacing
     */
    private function fixSpaceAt(Tokens $tokens, int $insertIndex, int $whitespaceIndex, string $spacing, bool $removeMultilineWhitespace): void
    {
        $token = $tokens[$whitespaceIndex];

        if ($token->isWhitespace()) {
            if (!$token->isWhitespace(" \t")) {
                // whitespace contains a line break
                if (self::SPACING_NONE === $spacing && $removeMultilineWhitespace) {
                    $tokens->clearAt($whitespaceIndex);
                }

                return;
            }

            if (self::SPACING_NONE === $spacing) {
                $tokens->clearAt($whitespaceIndex);
            } elseif (' ' !== $token->getContent()) {
                $tokens[$whitespaceIndex] = new Token([\T_WHITESPACE, ' ']);
            }

            return;
        }

        if (self::SPACING_SINGLE !== $spacing) {
            return;
        }

        // do not add a space next to a line break, e.g. after a single line comment that holds it
        $content = $tokens[$insertIndex - 1]->getContent();
        if ("\n" === substr($content, -1) || "\r" === substr($content, -1)) {
            return;
        }

        $tokens->insertAt($insertIndex, new Token([\T_WHITESPACE, ' ']));
    }
}
