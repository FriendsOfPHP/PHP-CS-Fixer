namespace PhpCsFixer\Fixer\Whitespace;

use PhpCsFixer\AbstractFixer;
use PhpCsFixer\Fixer\ConfigurableFixerInterface;
use PhpCsFixer\Fixer\ConfigurableFixerTrait;
use PhpCsFixer\FixerConfiguration\FixerConfigurationResolver;
use PhpCsFixer\FixerConfiguration\FixerConfigurationResolverInterface;
use PhpCsFixer\FixerConfiguration\FixerOptionBuilder;
use PhpCsFixer\FixerDefinition\CodeSample;
use PhpCsFixer\FixerDefinition\FixerDefinition;
use PhpCsFixer\FixerDefinition\FixerDefinitionInterface;
use PhpCsFixer\FixerDefinition\VersionSpecification;
use PhpCsFixer\FixerDefinition\VersionSpecificCodeSample;
use PhpCsFixer\Tokenizer\Analyzer\Analysis\SwitchAnalysis;
use PhpCsFixer\Tokenizer\Analyzer\ControlCaseStructuresAnalyzer;
use PhpCsFixer\Tokenizer\CT;
use PhpCsFixer\Tokenizer\Token;
use PhpCsFixer\Tokenizer\Tokens;

/**
 * @phpstan-type _AutogeneratedInputConfiguration array{
 *  space_before_case?: 'none'|'one',
 *  space_before_named_argument?: 'none'|'one',
 *  space_before_return_type?: 'none'|'one',
 * }
 * @phpstan-type _AutogeneratedComputedConfiguration array{
 *  space_before_case: 'none'|'one',
 *  space_before_named_argument: 'none'|'one',
 *  space_before_return_type: 'none'|'one',
 * }
 *
 * @implements ConfigurableFixerInterface<_AutogeneratedInputConfiguration, _AutogeneratedComputedConfiguration>
 *
 * @author Dariusz Rumiński <dariusz.ruminski@gmail.com>
 * @author Sullivan Senechal <soullivaneuh@gmail.com>
 *
 * @no-named-arguments Parameter names are not covered by the backward compatibility promise.
 */
final class ColonSpaceFixer extends AbstractFixer implements ConfigurableFixerInterface
{
    /** @use ConfigurableFixerTrait<_AutogeneratedInputConfiguration, _AutogeneratedComputedConfiguration> */
    use ConfigurableFixerTrait;

    public function getDefinition(): FixerDefinitionInterface
    {
        return new FixerDefinition(
            'Adjust spacing around the colon in return type declarations, backed enum types, named arguments, and switch case statements.',
            [
                new CodeSample(
                    <<<'PHP'
                        <?php
                            function foo(int $a):string {}

                            switch($a) {
                                case 1   :
                                    break;
                                default     :
                                    return 2;
                            }

                        PHP,
                ),
                new CodeSample(
                    "<?php\nfunction foo(int \$a):string {}\n",
                    ['space_before_return_type' => 'one'],
                ),
                new CodeSample(
                    "<?php\nswitch (\$a) {\n    case 1:\n        break;\n}\n",
                    ['space_before_case' => 'one'],
                ),
                new VersionSpecificCodeSample(
                    "<?php\n\nfoo(bar : 'baz');\n",
                    new VersionSpecification(8_00_00),
                ),
                new VersionSpecificCodeSample(
                    "<?php\n\nfoo(bar: 'baz');\n",
                    new VersionSpecification(8_00_00),
                    ['space_before_named_argument' => 'one'],
                ),
            ],
        );
    }

    /**
     * {@inheritdoc}
     *
     * Must run after PhpUnitDataProviderReturnTypeFixer, PhpdocToReturnTypeFixer, VoidReturnFixer.
     */
    public function getPriority(): int
    {
        return -17;
    }

    public function isCandidate(Tokens $tokens): bool
    {
        return $tokens->isAnyTokenKindsFound([CT::T_TYPE_COLON, CT::T_NAMED_ARGUMENT_COLON, \T_SWITCH]);
    }

    protected function applyFix(\SplFileInfo $file, Tokens $tokens): void
    {
        $this->fixTypeAndNamedArgumentColons(
            $tokens,
            'one' === $this->configuration['space_before_return_type'],
            'one' === $this->configuration['space_before_named_argument'],
        );

        $this->fixSwitchCaseColons($tokens, 'one' === $this->configuration['space_before_case']);
    }

    protected function createConfigurationDefinition(): FixerConfigurationResolverInterface
    {
        return new FixerConfigurationResolver([
            (new FixerOptionBuilder('space_before_case', 'Spacing to apply before the colon of a `case` or `default` statement.'))
                ->setAllowedValues(['one', 'none'])
                ->setDefault('none')
                ->getOption(),
            (new FixerOptionBuilder('space_before_named_argument', 'Spacing to apply before the colon of a named argument.'))
                ->setAllowedValues(['one', 'none'])
                ->setDefault('none')
                ->getOption(),
            (new FixerOptionBuilder('space_before_return_type', 'Spacing to apply before the colon of a return type declaration or backed enum type.'))
                ->setAllowedValues(['one', 'none'])
                ->setDefault('none')
                ->getOption(),
        ]);
    }

    private function fixTypeAndNamedArgumentColons(Tokens $tokens, bool $oneSpaceBeforeReturnType, bool $oneSpaceBeforeNamedArgument): void
    {
        for ($index = 0, $limit = $tokens->count(); $index < $limit; ++$index) {
            if (!$tokens[$index]->isGivenKind([CT::T_TYPE_COLON, CT::T_NAMED_ARGUMENT_COLON])) {
                continue;
            }

            $oneSpaceBefore = $tokens[$index]->isGivenKind(CT::T_TYPE_COLON)
                ? $oneSpaceBeforeReturnType
                : $oneSpaceBeforeNamedArgument;

            $previousIndex = $index - 1;

            if (!$tokens[$previousIndex]->isWhitespace() || !$tokens[$tokens->getPrevNonWhitespace($previousIndex)]->isComment()) {
                $tokenWasAdded = $this->fixSpaceBeforeColon($tokens, $index, $oneSpaceBefore);

                if ($tokenWasAdded) {
                    ++$limit;
                    ++$index;
                }
            }

            ++$index;

            $tokenWasAdded = $tokens->ensureWhitespaceAtIndex($index, 0, ' ');

            if ($tokenWasAdded) {
                ++$limit;
            }
        }
    }

    private function fixSwitchCaseColons(Tokens $tokens, bool $oneSpaceBefore): void
    {
        $colonIndexes = [];

        /** @var SwitchAnalysis $analysis */
        foreach (ControlCaseStructuresAnalyzer::findControlStructures($tokens, [\T_SWITCH]) as $analysis) {
            $default = $analysis->getDefaultAnalysis();

            if (null !== $default) {
                $colonIndexes[] = $default->getColonIndex();
            }

            foreach ($analysis->getCases() as $caseAnalysis) {
                $colonIndexes[] = $caseAnalysis->getColonIndex();
            }
        }

        rsort($colonIndexes);

        foreach ($colonIndexes as $colonIndex) {
            // skip if space is after comment
            if ($tokens[$tokens->getPrevNonWhitespace($colonIndex)]->isComment()) {
                continue;
            }

            $this->fixSpaceBeforeColon($tokens, $colonIndex, $oneSpaceBefore);
        }
    }

    /**
     * @return bool whether a token was inserted before the colon
     */
    private function fixSpaceBeforeColon(Tokens $tokens, int $colonIndex, bool $oneSpaceBefore): bool
    {
        $previousIndex = $colonIndex - 1;

        if ($tokens[$previousIndex]->isWhitespace()) {
            if ($oneSpaceBefore) {
                $tokens[$previousIndex] = new Token([\T_WHITESPACE, ' ']);
            } else {
                $tokens->clearAt($previousIndex);
            }
        } elseif ($oneSpaceBefore) {
            $tokens->ensureWhitespaceAtIndex($colonIndex, 0, ' ');

            return true;
        }

        return false;
    }
}
