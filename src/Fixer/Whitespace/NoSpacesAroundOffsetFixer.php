namespace PhpCsFixer\Fixer\Whitespace;

use PhpCsFixer\AbstractProxyFixer;
use PhpCsFixer\Fixer\ConfigurableFixerInterface;
use PhpCsFixer\Fixer\ConfigurableFixerTrait;
use PhpCsFixer\Fixer\DeprecatedFixerInterface;
use PhpCsFixer\FixerConfiguration\AllowedValueSubset;
use PhpCsFixer\FixerConfiguration\FixerConfigurationResolver;
use PhpCsFixer\FixerConfiguration\FixerConfigurationResolverInterface;
use PhpCsFixer\FixerConfiguration\FixerOptionBuilder;
use PhpCsFixer\FixerDefinition\CodeSample;
use PhpCsFixer\FixerDefinition\FixerDefinition;
use PhpCsFixer\FixerDefinition\FixerDefinitionInterface;

/**
 * @deprecated in favour of SpacesAroundOffsetFixer
 *
 * @phpstan-type _AutogeneratedInputConfiguration array{
 *  positions?: list<'inside'|'outside'>,
 * }
 * @phpstan-type _AutogeneratedComputedConfiguration array{
 *  positions: list<'inside'|'outside'>,
 * }
 *
 * @implements ConfigurableFixerInterface<_AutogeneratedInputConfiguration, _AutogeneratedComputedConfiguration>
 *
 * @author Javier Spagnoletti <phansys@gmail.com>
 *
 * @no-named-arguments Parameter names are not covered by the backward compatibility promise.
 */
final class NoSpacesAroundOffsetFixer extends AbstractProxyFixer implements ConfigurableFixerInterface, DeprecatedFixerInterface
{
    /** @use ConfigurableFixerTrait<_AutogeneratedInputConfiguration, _AutogeneratedComputedConfiguration> */
    use ConfigurableFixerTrait;

    private SpacesAroundOffsetFixer $spacesAroundOffsetFixer;

    public function __construct()
    {
        $this->spacesAroundOffsetFixer = new SpacesAroundOffsetFixer();

        parent::__construct();
    }

    public function getDefinition(): FixerDefinitionInterface
    {
        return new FixerDefinition(
            'There MUST NOT be spaces around offset braces.',
            [
                new CodeSample("<?php\n\$sample = \$b [ 'a' ] [ 'b' ];\n"),
                new CodeSample("<?php\n\$sample = \$b [ 'a' ] [ 'b' ];\n", ['positions' => ['inside']]),
                new CodeSample("<?php\n\$sample = \$b [ 'a' ] [ 'b' ];\n", ['positions' => ['outside']]),
            ],
        );
    }

    public function getSuccessorsNames(): array
    {
        return array_keys($this->proxyFixers);
    }

    protected function configurePostNormalisation(): void
    {
        $this->spacesAroundOffsetFixer->configure([
            'spacing' => [
                'inside' => \in_array('inside', $this->configuration['positions'], true)
                    ? SpacesAroundOffsetFixer::SPACING_NONE
                    : SpacesAroundOffsetFixer::SPACING_IGNORE,
                'outside' => \in_array('outside', $this->configuration['positions'], true)
                    ? SpacesAroundOffsetFixer::SPACING_NONE
                    : SpacesAroundOffsetFixer::SPACING_IGNORE,
            ],
        ]);
    }

    protected function createProxyFixers(): array
    {
        return [$this->spacesAroundOffsetFixer];
    }

    protected function createConfigurationDefinition(): FixerConfigurationResolverInterface
    {
        $values = ['inside', 'outside'];

        return new FixerConfigurationResolver([
            (new FixerOptionBuilder('positions', 'Whether spacing should be fixed inside and/or outside the offset braces.'))
                ->setAllowedTypes(['string[]'])
                ->setAllowedValues([new AllowedValueSubset($values)])
                ->setDefault($values)
                ->getOption(),
        ]);
    }
}
