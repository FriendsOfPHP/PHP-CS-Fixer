    public function testInvalidConfiguration(): void
    {
        $this->expectException(InvalidFixerConfigurationException::class);
        $this->expectExceptionMessageMatches(
            '#^\[colon_space\] Invalid configuration: The option "s" does not exist\. (Known|Defined) options are: "space_before_case", "space_before_named_argument", "space_before_return_type"\.$#',
        );

        $this->fixer->configure(['s' => 9_000]); // @phpstan-ignore argument.type
    }

    /**
     * @param _AutogeneratedInputConfiguration $configuration
     *
     * @dataProvider provideFixCases
