    /**
     * @return iterable<int, array{string, string, _AutogeneratedInputConfiguration}>
     */
    public static function provideFix80Cases(): iterable
    {
        foreach (self::provideMultiDimensionalArrayCases() as $index => $test) {
            $test[0] = str_replace('{', '[', $test[0]);
            $test[0] = str_replace('}', ']', $test[0]);
            $test[1] = str_replace('{', '[', $test[1]);
            $test[1] = str_replace('}', ']', $test[1]);

            yield $index => $test;
        }
    }

    /**
     * @return iterable<string, array{string, null|string, _AutogeneratedInputConfiguration}>
     */
    private static function provideSpacingCases(): iterable
    {
        yield 'partial configuration is merged with default' => [
            '<?php $a[ 1 ];',
            '<?php $a  [1];',
            ['spacing' => ['inside' => 'single']],
        ];

        $input = '<?php $i  [  1  ]; $j[1];';

        $matrix = [
            'none' => [
                'none' => '<?php $i[1]; $j[1];',
                'single' => '<?php $i [1]; $j [1];',
                'ignore' => '<?php $i  [1]; $j[1];',
            ],
            'single' => [
                'none' => '<?php $i[ 1 ]; $j[ 1 ];',
                'single' => '<?php $i [ 1 ]; $j [ 1 ];',
                'ignore' => '<?php $i  [ 1 ]; $j[ 1 ];',
            ],
            'ignore' => [
                'none' => '<?php $i[  1  ]; $j[1];',
                'single' => '<?php $i [  1  ]; $j [1];',
                'ignore' => '<?php $i  [  1  ]; $j[1];',
            ],
        ];

        foreach ($matrix as $inside => $outsides) {
            foreach ($outsides as $outside => $expected) {
                yield \sprintf('inside %s, outside %s', $inside, $outside) => [
                    $expected,
                    $expected === $input ? null : $input,
                    ['spacing' => ['inside' => $inside, 'outside' => $outside]],
                ];
            }
        }

        yield 'single/single chained' => [
            '<?php $b [ \'a\' ] [ \'b\' ];',
            '<?php $b[\'a\'][\'b\'];',
            ['spacing' => ['inside' => 'single', 'outside' => 'single']],
        ];

        yield 'single/single normalizes tabs and multiple spaces' => [
            '<?php $b [ \'a\' ] [ \'b\' ];',
            "<?php \$b\t[\t'a'   ]   [  'b'\t];",
            ['spacing' => ['inside' => 'single', 'outside' => 'single']],
        ];

        yield 'single inside nested' => [
            '<?php $a[ $b[ $c ] ];',
            '<?php $a[$b[$c]];',
            ['spacing' => ['inside' => 'single', 'outside' => 'none']],
        ];

        yield 'single outside on call result, property and static access' => [
            '<?php foo() [0]; $a->b [1]; A::$b [2]; A::B [3];',
            '<?php foo()[0]; $a->b[1]; A::$b[2]; A::B[3];',
            ['spacing' => ['inside' => 'none', 'outside' => 'single']],
        ];

        yield 'single inside keeps empty offset empty' => [
            '<?php $a[] = 1; $b[] = 2;',
            '<?php $a[] = 1; $b[  ] = 2;',
            ['spacing' => ['inside' => 'single', 'outside' => 'none']],
        ];

        yield 'single inside keeps line breaks' => [
            "<?php \$a[\n    1\n];",
            null,
            ['spacing' => ['inside' => 'single', 'outside' => 'none']],
        ];

        yield 'single outside keeps line breaks' => [
            "<?php \$a [0]\n    [1];",
            "<?php \$a[0]\n    [1];",
            ['spacing' => ['inside' => 'none', 'outside' => 'single']],
        ];

        yield 'single inside with comments' => [
            '<?php $a[ /* x */ 1 /* y */ ];',
            '<?php $a[/* x */ 1 /* y */];',
            ['spacing' => ['inside' => 'single', 'outside' => 'none']],
        ];

        yield 'single outside skips when preceded by comment' => [
            "<?php \$a [0] // comment\n[1] /* c */[2];",
            "<?php \$a[0] // comment\n[1] /* c */[2];",
            ['spacing' => ['inside' => 'none', 'outside' => 'single']],
        ];

        yield 'single does not touch simple string interpolation' => [
            '<?php echo "$a[1] $b[c] $d[$e] {$f [ 1 ]}"; echo `$g[1]`;',
            '<?php echo "$a[1] $b[c] $d[$e] {$f[1]}"; echo `$g[1]`;',
            ['spacing' => ['inside' => 'single', 'outside' => 'single']],
        ];

        yield 'single does not touch simple heredoc interpolation' => [
            "<?php echo <<<EOT\n\$a[1] {\$b [ 1 ]}\nEOT;\n\$c [ 1 ];",
            "<?php echo <<<EOT\n\$a[1] {\$b[1]}\nEOT;\n\$c[1];",
            ['spacing' => ['inside' => 'single', 'outside' => 'single']],
        ];

        yield 'single handles nested strings in complex interpolation' => [
            '<?php echo "{$a [ "x" ]} $b[1]"; $c [ 1 ];',
            '<?php echo "{$a["x"]} $b[1]"; $c[1];',
            ['spacing' => ['inside' => 'single', 'outside' => 'single']],
        ];

        yield 'does not touch array literals, destructuring and attributes' => [
            "<?php #[A]\nfunction f() { [\$a, \$b] = [1, 2]; \$c [ 1 ]; }",
            "<?php #[A]\nfunction f() { [\$a, \$b] = [1, 2]; \$c[1]; }",
            ['spacing' => ['inside' => 'single', 'outside' => 'single']],
        ];
    }

    /**
     * @return iterable<int, array{string, string, _AutogeneratedInputConfiguration}>
     */
    private static function provideMultiDimensionalArrayCases(): iterable
    {
        yield [
            <<<'EOT'
                <?php
                $arr1[]  ["some_offset"] [] {"foo"} = 3;
                EOT,
            <<<'EOT'
                <?php
                $arr1[  ]  [ "some_offset"   ] [     ] { "foo" } = 3;
                EOT,
            ['spacing' => ['inside' => 'none', 'outside' => 'ignore']],
        ];

        yield [
            <<<'EOT'
                <?php
                $arr1[  ][ "some_offset"   ][     ]{ "foo" } = 3;
                EOT,
            <<<'EOT'
                <?php
                $arr1[  ]  [ "some_offset"   ] [     ] { "foo" } = 3;
                EOT,
            ['spacing' => ['inside' => 'ignore', 'outside' => 'none']],
        ];
    }
