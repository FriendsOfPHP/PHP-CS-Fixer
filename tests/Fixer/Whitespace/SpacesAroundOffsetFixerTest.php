            '/^\[spaces_around_offset\] Invalid configuration: Unexpected spacing for position "inside".*$/',
        ];

        yield 'not an array' => [
            ['spacing' => 'none'],
            '/^\[spaces_around_offset\] Invalid configuration: The option "spacing" .*$/',
        ];
    }

