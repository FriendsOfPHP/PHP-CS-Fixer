namespace PhpCsFixer\Tests\Fixer\Phpdoc;

use PhpCsFixer\Fixer\Phpdoc\PhpdocNullableTypeFixer;
use PhpCsFixer\Tests\Test\AbstractFixerTestCase;
use PHPUnit\Framework\Attributes\CoversClass;
use PHPUnit\Framework\Attributes\DataProvider;

/**
 * @internal
 *
 * @covers \PhpCsFixer\Fixer\Phpdoc\PhpdocNullableTypeFixer
 *
 * @extends AbstractFixerTestCase<\PhpCsFixer\Fixer\Phpdoc\PhpdocNullableTypeFixer>
 *
 * @phpstan-import-type _AutogeneratedInputConfiguration from \PhpCsFixer\Fixer\Phpdoc\PhpdocNullableTypeFixer
 *
 * @no-named-arguments Parameter names are not covered by the backward compatibility promise.
 */
#[CoversClass(PhpdocNullableTypeFixer::class)]
final class PhpdocNullableTypeFixerTest extends AbstractFixerTestCase
{
    /**
     * @param _AutogeneratedInputConfiguration $configuration
     *
     * @dataProvider provideFixCases
     */
    #[DataProvider('provideFixCases')]
    public function testFix(string $expected, ?string $input = null, array $configuration = []): void
    {
        $this->fixer->configure($configuration);

        $this->doTest($expected, $input);
    }

    /**
     * @return iterable<string, array{0: string, 1?: null|string, 2?: _AutogeneratedInputConfiguration}>
     */
    public static function provideFixCases(): iterable
    {
        yield 'null first' => [
            '<?php /** @var ?Foo */',
            '<?php /** @var null|Foo */',
        ];

        yield 'null last' => [
            '<?php /** @var ?Foo */',
            '<?php /** @var Foo|null */',
        ];

        yield 'generic type' => [
            '<?php /** @var ?iterable<\SplFileInfo> */',
            '<?php /** @var null|iterable<\SplFileInfo> */',
        ];

        yield 'parameter' => [
            '<?php /** @param ?Foo $foo */',
            '<?php /** @param null|Foo $foo */',
        ];

        yield 'return' => [
            '<?php /** @return ?Foo */',
            '<?php /** @return Foo|null */',
        ];

        yield 'union with more than two members is unchanged' => [
            '<?php /** @var null|Foo|Bar */',
        ];

        yield 'union without null is unchanged' => [
            '<?php /** @var Foo|Bar */',
        ];

        yield 'standalone null is unchanged' => [
            '<?php /** @var null */',
        ];

        yield 'explicit union syntax' => [
            '<?php /** @var null|Foo */',
            '<?php /** @var ?Foo */',
            ['syntax' => 'union'],
        ];

        yield 'explicit union syntax with generic' => [
            '<?php /** @var null|iterable<\SplFileInfo> */',
            '<?php /** @var ?iterable<\SplFileInfo> */',
            ['syntax' => 'union'],
        ];

        yield 'already question mark syntax is unchanged' => [
            '<?php /** @var ?Foo */',
        ];

        yield 'nested generic' => [
            '<?php /** @var array<?Foo> */',
            '<?php /** @var array<null|Foo> */',
        ];

        yield 'callable argument and nested return type' => [
            '<?php /** @var callable(?Foo): array<?Bar> */',
            '<?php /** @var callable(null|Foo): array<Bar|null> */',
        ];

        yield 'method return and parameter type' => [
            '<?php /** @method ?Foo doSomething(?Bar $bar) */',
            '<?php /** @method Foo|null doSomething(null|Bar $bar) */',
        ];

        yield 'uppercase null' => [
            '<?php /** @var ?Foo */',
            '<?php /** @var NULL|Foo */',
        ];

        yield 'two null types are unchanged' => [
            '<?php /** @var null|NULL */',
        ];

        yield 'parenthesized intersection' => [
            '<?php /** @var ?(Foo&Bar) */',
            '<?php /** @var null|(Foo&Bar) */',
        ];

        yield 'nested generic with union syntax' => [
            '<?php /** @var array<null|Foo> */',
            '<?php /** @var array<?Foo> */',
            ['syntax' => 'union'],
        ];

        yield 'method with union syntax' => [
            '<?php /** @method null|Foo doSomething(null|Bar $bar) */',
            '<?php /** @method ?Foo doSomething(?Bar $bar) */',
            ['syntax' => 'union'],
        ];

        yield 'null with already nullable type' => [
            '<?php /** @var ?Foo */',
            '<?php /** @var null|?Foo */',
        ];

        yield 'already nullable type with null last' => [
            '<?php /** @var ?Foo */',
            '<?php /** @var ?Foo|null */',
        ];

        yield 'null with already nullable type using union syntax' => [
            '<?php /** @var null|Foo */',
            '<?php /** @var null|?Foo */',
            ['syntax' => 'union'],
        ];

        yield 'unparenthesized intersection with null first' => [
            '<?php /** @var ?(Foo&Bar) */',
            '<?php /** @var null|Foo&Bar */',
        ];

        yield 'unparenthesized intersection with null last' => [
            '<?php /** @var ?(Foo&Bar) */',
            '<?php /** @var Foo&Bar|null */',
        ];

        yield 'namespaced class named null is not null' => [
            '<?php /** @var \null|Foo */',
        ];

        yield 'array suffix' => [
            '<?php /** @var ?Foo[] */',
            '<?php /** @var null|Foo[] */',
        ];

        yield 'larger union with nullable member using union syntax' => [
            '<?php /** @var null|Foo|Bar */',
            '<?php /** @var ?Foo|Bar */',
            ['syntax' => 'union'],
        ];

        yield 'callable parenthesized return union' => [
            '<?php /** @var callable(?Foo): (?Bar) */',
            '<?php /** @var callable(null|Foo): (Bar|null) */',
        ];

        yield 'method without explicit return type' => [
            '<?php /** @method doSomething(?Bar $bar) */',
            '<?php /** @method doSomething(null|Bar $bar) */',
        ];

        yield 'multiline array shape' => [
            <<<'PHP'
                <?php
                /**
                 * @return array{
                 *     foo: ?Foo,
                 *     bar: array<?Bar>,
                 * }
                 */
                PHP,
            <<<'PHP'
                <?php
                /**
                 * @return array{
                 *     foo: null|Foo,
                 *     bar: array<Bar|null>,
                 * }
                 */
                PHP,
        ];
    }
}
