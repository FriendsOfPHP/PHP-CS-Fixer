namespace PhpCsFixer\Tests\Fixer\Phpdoc;

use PhpCsFixer\Fixer\Phpdoc\PhpdocMultiLineThrowsFixer;
use PhpCsFixer\Tests\Test\AbstractFixerTestCase;
use PHPUnit\Framework\Attributes\CoversClass;
use PHPUnit\Framework\Attributes\DataProvider;

/**
 * @internal
 *
 * @covers \PhpCsFixer\Fixer\Phpdoc\PhpdocMultiLineThrowsFixer
 *
 * @extends AbstractFixerTestCase<\PhpCsFixer\Fixer\Phpdoc\PhpdocMultiLineThrowsFixer>
 *
 * @phpstan-import-type _AutogeneratedInputConfiguration from \PhpCsFixer\Fixer\Phpdoc\PhpdocMultiLineThrowsFixer
 *
 * @no-named-arguments Parameter names are not covered by the backward compatibility promise.
 */
#[CoversClass(PhpdocMultiLineThrowsFixer::class)]
final class PhpdocMultiLineThrowsFixerTest extends AbstractFixerTestCase
{
    /**
     * @param _AutogeneratedInputConfiguration $configuration
     *
     * @dataProvider provideFixCases
     */
    #[DataProvider('provideFixCases')]
    public function testFix(string $expected, ?string $input = null, array $configuration = []): void
    {
        $this->fixer->configure($configuration);
        $this->doTest($expected, $input);
    }

    /**
     * @return iterable<string, array{0: string, 1?: ?string, 2?: _AutogeneratedInputConfiguration}>
     */
    public static function provideFixCases(): iterable
    {
        yield 'no changes' => [<<<'EOF'
            <?php
                /**
                 * @throws RuntimeException|Throwable|Exception
                 * @throws OutOfBoundsException with a comment about this specific exception
                 * @throws OverFlowException|RangeException with a comment about this specific union exception
                 */

            EOF];

        yield 'multi line to union default' => [
            <<<'EOF'
                <?php
                    /**
                     * @throws InvalidArgumentException|RuntimeException|Throwable|Exception
                     */

                EOF,
            <<<'EOF'
                <?php
                    /**
                     * @throws InvalidArgumentException
                     * @throws RuntimeException
                     * @throws Throwable|Exception
                     */

                EOF,
        ];

        yield 'multi line to explicit union' => [
            <<<'EOF'
                <?php
                    /**
                     * @throws InvalidArgumentException|RuntimeException|Throwable|Exception
                     */

                EOF,
            <<<'EOF'
                <?php
                    /**
                     * @throws InvalidArgumentException
                     * @throws RuntimeException
                     * @throws Throwable|Exception
                     */

                EOF,
            ['format' => 'union'],
        ];

        yield 'multi line to union with single intersection' => [
            <<<'EOF'
                <?php
                    /**
                     * @throws InvalidArgumentException|RuntimeException|(Throwable&Exception)
                     */

                EOF,
            <<<'EOF'
                <?php
                    /**
                     * @throws InvalidArgumentException
                     * @throws RuntimeException
                     * @throws Throwable&Exception
                     */

                EOF,
            ['format' => 'union'],
        ];

        yield 'multi line to union with multiple intersections' => [
            <<<'EOF'
                <?php
                    /**
                     * @throws (InvalidArgumentException&RuntimeException)|(Throwable&Exception)
                     */

                EOF,
            <<<'EOF'
                <?php
                    /**
                     * @throws InvalidArgumentException&RuntimeException
                     * @throws Throwable&Exception
                     */

                EOF,
            ['format' => 'union'],
        ];

        yield 'multi line to union with comment on single throws' => [
            <<<'EOF'
                <?php
                    /**
                     * @throws InvalidArgumentException|Throwable|Exception
                     * @throws RuntimeException with a specific comment on one throws
                     */

                EOF,
            <<<'EOF'
                <?php
                    /**
                     * @throws InvalidArgumentException
                     * @throws RuntimeException with a specific comment on one throws
                     * @throws Throwable|Exception
                     */

                EOF,
            ['format' => 'union'],
        ];

        yield 'multi line to union with comment on union throws' => [
            <<<'EOF'
                <?php
                    /**
                     * @throws InvalidArgumentException|RuntimeException
                     * @throws Throwable|Exception with a specific comment on union throws
                     */

                EOF,
            <<<'EOF'
                <?php
                    /**
                     * @throws InvalidArgumentException
                     * @throws RuntimeException
                     * @throws Throwable|Exception with a specific comment on union throws
                     */

                EOF,
            ['format' => 'union'],
        ];

        yield 'union line to multi' => [
            <<<'EOF'
                <?php
                    /**
                     * @throws InvalidArgumentException
                     * @throws RuntimeException
                     * @throws Throwable
                     * @throws Exception
                     */

                EOF,
            <<<'EOF'
                <?php
                    /**
                     * @throws InvalidArgumentException|RuntimeException|Throwable|Exception
                     */

                EOF,
            ['format' => 'multi'],
        ];

        yield 'union line to multi with comment on union' => [
            <<<'EOF'
                <?php
                    /**
                     * @throws InvalidArgumentException|RuntimeException|Throwable|Exception with comment on union
                     */

                EOF,
            null,
            ['format' => 'multi'],
        ];
    }
}
