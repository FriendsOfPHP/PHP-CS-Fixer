namespace PhpCsFixer\Tests\Fixer\Alias;

use PhpCsFixer\ConfigurationException\InvalidFixerConfigurationException;
use PhpCsFixer\Fixer\Alias\MbStrFunctionsFixer;
use PhpCsFixer\Tests\Test\AbstractFixerTestCase;
use PHPUnit\Framework\Attributes\CoversClass;
use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\Attributes\RequiresPhp;

/**
 * @internal
 *
 * @covers \PhpCsFixer\Fixer\Alias\MbStrFunctionsFixer
 *
 * @extends AbstractFixerTestCase<\PhpCsFixer\Fixer\Alias\MbStrFunctionsFixer>
 *
 * @phpstan-import-type _AutogeneratedInputConfiguration from \PhpCsFixer\Fixer\Alias\MbStrFunctionsFixer
 *
 * @author Filippo Tessarotto <zoeslam@gmail.com>
 *
 * @no-named-arguments Parameter names are not covered by the backward compatibility promise.
 */
#[CoversClass(MbStrFunctionsFixer::class)]
final class MbStrFunctionsFixerTest extends AbstractFixerTestCase
{
    /**
     * @param _AutogeneratedInputConfiguration $configuration
     *
     * @dataProvider provideFixCases
     */
    #[DataProvider('provideFixCases')]
    public function testFix(string $expected, ?string $input = null, array $configuration = []): void
    {
        $this->fixer->configure($configuration);
        $this->doTest($expected, $input);
    }

    /**
     * @return iterable<array{0: string, 1?: null|string, 2?: _AutogeneratedInputConfiguration}>
     */
    public static function provideFixCases(): iterable
    {
        yield ['<?php $x = "strlen";'];

        yield ['<?php $x = Foo::strlen("bar");'];

        yield ['<?php $x = new strlen("bar");'];

        yield ['<?php $x = new \strlen("bar");'];

        yield ['<?php $x = new Foo\strlen("bar");'];

        yield ['<?php $x = Foo\strlen("bar");'];

        yield ['<?php $x = strlen::call("bar");'];

        yield ['<?php $x = $foo->strlen("bar");'];

        yield ['<?php $x = strlen();']; // number of arguments mismatch

        yield ['<?php $x = strlen($a, $b);']; // number of arguments mismatch

        yield ['<?php $x = mb_strlen("bar");', '<?php $x = strlen("bar");'];

        yield ['<?php $x = \mb_strlen("bar");', '<?php $x = \strlen("bar");'];

        yield ['<?php $x = mb_strtolower(mb_strstr("bar", "a"));', '<?php $x = strtolower(strstr("bar", "a"));'];

        yield ['<?php $x = mb_strtolower( \mb_strstr ("bar", "a"));', '<?php $x = strtolower( \strstr ("bar", "a"));'];

        yield ['<?php $x = mb_substr("bar", 2, 1);', '<?php $x = substr("bar", 2, 1);'];

        yield [
            '<?php
                interface Test
                {
                    public function &strlen($a);
                    public function strtolower($a);
                }',
        ];

        yield [
            '<?php $a = mb_str_split($a);',
            '<?php $a = str_split($a);',
        ];

        yield [
            <<<'PHP'
                <?php
                namespace Foo;
                use function Bar\strlen;
                use function mb_strtolower;
                use function mb_strtoupper;
                use function \mb_str_split;
                return strlen($x) > 10 ? mb_strtolower($x) : mb_strtoupper($x);
                PHP,
            <<<'PHP'
                <?php
                namespace Foo;
                use function Bar\strlen;
                use function strtolower;
                use function strtoupper;
                use function \str_split;
                return strlen($x) > 10 ? strtolower($x) : strtoupper($x);
                PHP,
        ];

        yield 'only configured functions' => [
            '<?php $a = mb_strlen($a); $b = strpos($a, $b); $c = str_split($a);',
            '<?php $a = strlen($a); $b = strpos($a, $b); $c = str_split($a);',
            ['functions' => ['strlen']],
        ];

        yield 'only configured function imports' => [
            '<?php use function mb_strlen; use function strpos;',
            '<?php use function strlen; use function strpos;',
            ['functions' => ['strlen']],
        ];

        yield 'no configured functions' => [
            '<?php $a = strlen($a); $b = strpos($a, $b);',
            null,
            ['functions' => []],
        ];
    }

    /**
     * @param array<array-key, mixed> $configuration
     *
     * @dataProvider provideInvalidConfigurationCases
     */
    #[DataProvider('provideInvalidConfigurationCases')]
    public function testInvalidConfiguration(array $configuration, string $expectedExceptionMessage): void
    {
        $this->expectException(InvalidFixerConfigurationException::class);
        $this->expectExceptionMessage($expectedExceptionMessage);

        $this->fixer->configure($configuration); // @phpstan-ignore argument.type
    }

    /**
     * @return iterable<string, array{array<array-key, mixed>, string}>
     */
    public static function provideInvalidConfigurationCases(): iterable
    {
        yield 'unknown function' => [
            ['functions' => ['mb_strlen']],
            '[mb_str_functions] Invalid configuration: The option "functions" with value array is invalid.',
        ];

        yield 'non-string function' => [
            ['functions' => [1]],
            '[mb_str_functions] Invalid configuration: The option "functions" with value array is expected to be of type "string[]", but one of the elements is of type "int".',
        ];
    }

    /**
     * @param _AutogeneratedInputConfiguration $configuration
     *
     * @requires PHP >= 8.3.0
     *
     * @dataProvider provideFix83Cases
     */
    #[RequiresPhp('>= 8.3.0')]
    #[DataProvider('provideFix83Cases')]
    public function testFix83(string $expected, ?string $input = null, array $configuration = []): void
    {
        $this->fixer->configure($configuration);
        $this->doTest($expected, $input);
    }

    /**
     * @return iterable<string, array{0: string, 1?: null|string, 2?: _AutogeneratedInputConfiguration}>
     */
    public static function provideFix83Cases(): iterable
    {
        yield 'mb_str_pad()' => [
            '<?php $x = mb_str_pad("bar", 2, "0", STR_PAD_LEFT);',
            '<?php $x = str_pad("bar", 2, "0", STR_PAD_LEFT);',
        ];

        yield 'str_pad() not configured' => [
            '<?php $x = str_pad("bar", 2, "0", STR_PAD_LEFT); $y = mb_strlen($x);',
            '<?php $x = str_pad("bar", 2, "0", STR_PAD_LEFT); $y = strlen($x);',
            ['functions' => ['strlen']],
        ];
    }

    /**
     * @requires PHP < 8.4.0
     *
     * @dataProvider provideFixPre84Cases
     */
    #[RequiresPhp('< 8.4.0')]
    #[DataProvider('provideFixPre84Cases')]
    public function testFixPre84(string $expected, ?string $input = null): void
    {
        $this->doTest($expected, $input);
    }

    /**
     * @return iterable<string, array{0: string, 1?: null|string}>
     */
    public static function provideFixPre84Cases(): iterable
    {
        yield 'trim(), ltrim() and rtrim() without mb_* alternatives' => [
            '<?php $x = trim(ltrim(rtrim("    foo  "))); $y = mb_strlen($x);',
            '<?php $x = trim(ltrim(rtrim("    foo  "))); $y = strlen($x);',
        ];
    }

    /**
     * @param _AutogeneratedInputConfiguration $configuration
     *
     * @requires PHP >= 8.4.0
     *
     * @dataProvider provideFix84Cases
     */
    #[RequiresPhp('>= 8.4.0')]
    #[DataProvider('provideFix84Cases')]
    public function testFix84(string $expected, ?string $input = null, array $configuration = []): void
    {
        $this->fixer->configure($configuration);
        $this->doTest($expected, $input);
    }

    /**
     * @return iterable<string, array{0: string, 1?: null|string, 2?: _AutogeneratedInputConfiguration}>
     */
    public static function provideFix84Cases(): iterable
    {
        yield 'mb_trim 1 argument' => [
            '<?php $x = mb_trim("    foo  ");',
            '<?php $x = trim("    foo  ");',
        ];

        yield 'mb_trim 2 arguments' => [
            '<?php $x = mb_trim("____foo__", "_");',
            '<?php $x = trim("____foo__", "_");',
        ];

        yield 'ltrim' => [
            '<?php $x = mb_ltrim("    foo  ");',
            '<?php $x = ltrim("    foo  ");',
        ];

        yield 'rtrim' => [
            '<?php $x = mb_rtrim("    foo  ");',
            '<?php $x = rtrim("    foo  ");',
        ];

        yield 'trim(), ltrim() and rtrim() not configured' => [
            '<?php $x = trim(ltrim(rtrim("    foo  "))); $y = mb_strlen($x);',
            '<?php $x = trim(ltrim(rtrim("    foo  "))); $y = strlen($x);',
            ['functions' => ['strlen']],
        ];
    }
}
